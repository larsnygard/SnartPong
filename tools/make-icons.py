#!/usr/bin/env python3
"""Regenerate the SnartPong app icons.

The SVGs below are the source of truth for the icon artwork: the same Pong
screen (paddles, ball, dashed centre line) is emitted twice, once as a
rounded icon (transparent corners, used for the favicon and the manifest's
"any" icons) and once as a full-bleed square whose art sits inside the 80%
safe zone (the "maskable" icons Android crops to whatever shape the launcher
uses, plus the iOS touch icon).

    python3 tools/make-icons.py        # writes icons/*.svg and icons/*.png

Rendering PNGs needs one of rsvg-convert or ImageMagick (`magick`/`convert`).
No other dependencies; the SVGs are committed so the PNGs can also be
regenerated by hand from the command line.
"""
import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.join(os.path.dirname(HERE), "icons")

# ---- artwork ---------------------------------------------------------
SIZE = 512
BG = "#000000"
WHITE = "#ffffff"

# The Pong screen, scaled to the icon. Paddles near the edges, a ball in
# play, and the dashed centre line — the whole game in one glance.
PADDLE_W = 20
PADDLE_H = 150
PADDLE_MARGIN = 58
BALL = 24
BALL_X = 300
BALL_Y = 180
CENTER_X = SIZE // 2
DASH_H = 28
DASH_W = 10
DASH_GAP = 22
DASH_TOP = 40
MASK_SAFE_SCALE = 0.84   # art must stay inside the middle 80% of a maskable icon


def dashes():
    out = []
    y = DASH_TOP
    while y + DASH_H <= SIZE - 40:
        out.append(
            '    <rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>'
            % (CENTER_X - DASH_W // 2, y, DASH_W, DASH_H, WHITE)
        )
        y += DASH_H + DASH_GAP
    return "\n".join(out)


def artwork():
    parts = [
        # left paddle, right paddle, ball
        '    <rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>'
        % (PADDLE_MARGIN, (SIZE - PADDLE_H) // 2, PADDLE_W, PADDLE_H, WHITE),
        '    <rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>'
        % (SIZE - PADDLE_MARGIN - PADDLE_W, (SIZE - PADDLE_H) // 2 + 40,
           PADDLE_W, PADDLE_H, WHITE),
        '    <rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>'
        % (BALL_X, BALL_Y, BALL, BALL, WHITE),
        # dashed centre line
        dashes(),
    ]
    return "\n".join(parts)


def svg(maskable=False):
    bg = ('<rect x="0" y="0" width="%d" height="%d" fill="%s"/>' % (SIZE, SIZE, BG)
          if maskable else
          '<rect x="0" y="0" width="%d" height="%d" rx="96" fill="%s"/>' % (SIZE, SIZE, BG))
    art = artwork()
    if maskable:
        c = SIZE / 2.0
        s = MASK_SAFE_SCALE
        art = ('  <g transform="translate(%s %s) scale(%s) translate(%s %s)">' % (
            c, c, s, -c, -c)) + art + "\n  </g>"
        art = art
    return """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">
  <title>SnartPong</title>
  %s
%s
</svg>
""" % (SIZE, SIZE, SIZE, SIZE, bg, art)


# ---- rendering -------------------------------------------------------
def renderer():
    if shutil.which("rsvg-convert"):
        def rsvg(src, dst, px):
            subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), "-o", dst, src],
                           check=True)
        return rsvg
    for exe in ("magick", "convert"):
        if shutil.which(exe):
            def im(src, dst, px, exe=exe):
                subprocess.run([exe, "-background", "none", "-resize", "%dx%d" % (px, px),
                                src, dst], check=True)
            return im
    sys.exit("need rsvg-convert or ImageMagick to render PNGs (SVGs are written anyway)")


def png_size(path):
    with open(path, "rb") as fh:
        head = fh.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("%s is not a PNG" % path)
    return struct.unpack(">II", head[16:24])


def main():
    os.makedirs(ICONS, exist_ok=True)
    svgs = {
        "icon.svg": svg(maskable=False),
        "icon-maskable.svg": svg(maskable=True),
    }
    for name, markup in svgs.items():
        with open(os.path.join(ICONS, name), "w") as fh:
            fh.write(markup)
        print("wrote icons/%s" % name)

    render = renderer()
    targets = [
        ("icon.svg", "icon-192.png", 192),
        ("icon.svg", "icon-512.png", 512),
        ("icon.svg", "favicon-32.png", 32),
        ("icon-maskable.svg", "icon-maskable-192.png", 192),
        ("icon-maskable.svg", "icon-maskable-512.png", 512),
        ("icon-maskable.svg", "apple-touch-icon-180.png", 180),
    ]
    for src, dst, px in targets:
        out = os.path.join(ICONS, dst)
        render(os.path.join(ICONS, src), out, px)
        w, h = png_size(out)
        print("wrote icons/%-28s %dx%d  %d bytes" % (dst, w, h, os.path.getsize(out)))


if __name__ == "__main__":
    main()
